<h2>// HOW IT WAS USED</h2>
<p>The A1200 was mainly a games machine. AGA titles such as <em>Banshee</em>, <em>Alien Breed 3D</em>, <em>Gloom</em> and <em>Super Stardust</em> showed off the new chipset. It also had a lively demoscene. With a hard disk and a trapdoor accelerator it could do serious work too, including music in OctaMED, art in Deluxe Paint, and video titling and 3D rendering. Its hardware was the basis for the <a href="/blog/amiga-cd32">CD32</a> console.</p>

