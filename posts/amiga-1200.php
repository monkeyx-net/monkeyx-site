<p>A new machine has joined the collection: a <strong>Commodore Amiga 1200</strong> in its original box. It still has the polystyrene end caps, the Commodore power supply, the mouse, the leads and the multi-language information sheet. The case is only lightly yellowed.</p>

<h2>// HISTORY</h2>
<p>Commodore launched the A1200 in late 1992 at £399, as the successor to the hugely popular Amiga 500. It introduced the AGA (Advanced Graphics Architecture) chipset to the home Amiga. That raised the colour limit from 32 to 256 on screen, chosen from a palette of 16.8 million. It also came with a faster 68EC020 processor and twice the memory.</p>
<p>The A1200 sold well in the UK and Germany, but Commodore went bankrupt in April 1994, only 18 months after it launched. Later owners, including Escom, brought it back into production for a short time. The machine still has a big community, and accelerator cards, hard disk upgrades and new games are still being made for it.</p>

