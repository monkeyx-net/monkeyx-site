<h2>// HOW IT WAS USED</h2>
<p>The CD32 was a games console. Many of its games were Amiga titles moved to CD, sometimes with CD audio soundtracks or extra intros added. A few took more advantage of the hardware, such as <em>Microcosm</em> with its full-motion video. Add-ons such as the SX-1 and SX32 turned it into a full Amiga computer with a keyboard and floppy drive. It also had an add-on that played Video CDs.</p>

