<p>A new machine has joined the collection: a Commodore <strong>Amiga CD32</strong>. It comes with a power supply, AV leads, the official controller and a Competition Pro Super CD32 pad with its leaflet. There's also a stack of games: <em>Brutal Football</em>, <em>Zool</em>, <em>Bump 'n' Burn</em>, <em>Microcosm</em>, <em>PGA European Tour</em> and <em>Jungle Strike</em>, plus some CDs in cases.</p>

<h2>// HISTORY</h2>
<p>Commodore launched the CD32 in Europe in September 1993. It was essentially an <a href="/blog/amiga-1200">Amiga 1200</a> with the keyboard and floppy drive taken out and a double-speed CD-ROM drive added. It went on sale for £299 and was advertised as the first 32-bit CD console in Europe, beating Sony's PlayStation and the Sega Saturn to market.</p>
<p>For a few months it sold well in the UK. But Commodore was already in deep financial trouble and went bankrupt in April 1994. Production stopped, and a planned US launch was cancelled because of a patent dispute. The CD32 turned out to be the last machine Commodore ever released.</p>

