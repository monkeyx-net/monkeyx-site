<h2>// HOW IT WAS USED</h2>
<p>The PET found a home in schools, especially in the UK and North America, where it introduced many students to programming. It was also used in small businesses and labs. Its IEEE-488 port made it a handy controller for scientific instruments. The PETSCII character set let people draw on screen with block graphics, and hobbyists used it to write early text and graphics games.</p>

