<p>A new machine has joined the collection: an original <strong>Commodore PET 2001</strong>. This is the early design, with the small chiclet keyboard and the cassette deck built into the case. The case has scuffs and marks, but all the parts are there.</p>

<h2>// HISTORY</h2>
<p>The PET (Personal Electronic Transactor) was designed by Chuck Peddle, who also designed the 6502 CPU. Commodore showed it in January 1977 and began shipping it later that year. Along with the Apple II and the TRS-80, it was one of the three machines of 1977 that sold computers to ordinary buyers ready to use, with no kit to build. It cost $795 for the 8K model.</p>
<p>The original PET was criticised for its tiny keyboard. In 1979 Commodore replaced it with the 2001-N, which had a full-size keyboard and an external cassette drive. That makes these first machines with the built-in deck especially collectable.</p>

